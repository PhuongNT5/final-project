#!/usr/bin/env python3
"""F12: Export per-clip logits, probabilities, predictions for the 64-clip
4-class unsafe test set under CC BY 4.0 attribution.

Output: deployment/artifacts/per-clip-logits-test64.csv
Header includes:
  - clip_index   (0..63)
  - true_label   (0..3)
  - true_class
  - direct4_logit_{0..3}
  - direct4_prob_{0..3}
  - cascade_prob_{0..3}
  - ensemble_prob_{0..3}
  - ensemble_pred
  - ensemble_correct (0/1)

License header at top of file:
  Per-clip predictions on the Unsafe-Net 4-class unsafe test subset (N = 64).
  CC BY 4.0 — required attribution: cite Önal & Dandıl (2024) [17] for the
  underlying video clips and this thesis for the per-clip predictions.
"""
import os, sys, csv, importlib.util
import numpy as np
import torch
import torch.nn.functional as F

ROOT = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, ROOT)
CKPT = os.path.join(ROOT, 'sweep_results', 'pairwise')
FEAT_TE = os.path.join(CKPT, 'features', 'all8_test.pt')
OUT = os.path.join(ROOT, 'deployment', 'artifacts', 'per-clip-logits-test64.csv')
PAIRS = [(0, 4), (1, 5), (2, 6), (3, 7)]
PAIR_NAMES = ['Walkway', 'Intervention', 'Panel', 'Forklift']
CLASS_NAMES = ['WalkwayViol', 'UnauthorInt', 'OpenedPanel', 'CarryOverload']

LICENSE_HEADER = (
    "# Per-clip ensemble predictions on Unsafe-Net 4-class unsafe test subset (N = 64)\n"
    "# Generated by run_export_perclip_csv.py from sweep_results/pairwise/*.pt heads\n"
    "# Ensemble: 0.5 * direct4_s314 + 0.5 * (scenario_s7 x pair{0..3}_s7) cascade\n"
    "# License: CC BY 4.0 (https://creativecommons.org/licenses/by/4.0/)\n"
    "# Attribution required: K. B. Onal and E. Dandil, 'Unsafe-Net: YOLO v4 and ConvLSTM\n"
    "#   based computer vision system for real-time detection of unsafe behaviours in workplace,'\n"
    "#   Multimedia Tools and Applications, vol. 84, pp. 34967-34993, 2025.\n"
    "#   DOI: 10.1007/s11042-024-19276-8 (for the underlying video data)\n"
    "# Plus: this thesis for the per-clip predictions.\n"
)


def load_TH():
    spec = importlib.util.spec_from_file_location('pw', os.path.join(ROOT, 'run_pairwise_contrastive.py'))
    m = importlib.util.module_from_spec(spec); spec.loader.exec_module(m); return m.TransformerHead


def stats_pool(f):
    return torch.cat([f.mean(2), f.std(2), f.max(2).values], -1)


@torch.no_grad()
def head_logits(model, x, dev, bs=32):
    model.eval(); out = []
    for i in range(0, len(x), bs):
        out.append(model(x[i:i + bs].to(dev)).cpu())
    return torch.cat(out, 0).numpy()


def load_head(p, nc, dim, nh, L, sd, dev, TH):
    m = TH(sd, nc, dim, nh, L, 0.3).to(dev)
    m.load_state_dict(torch.load(p, map_location=dev, weights_only=True))
    return m


def main():
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    dev = torch.device('mps' if torch.backends.mps.is_available()
                       else 'cuda' if torch.cuda.is_available() else 'cpu')
    print(f"Device: {dev}")
    TH = load_TH()

    dte = torch.load(FEAT_TE, map_location='cpu', weights_only=False)
    mask4 = (dte['labels'] < 4).numpy()
    y = dte['labels'][mask4].numpy()
    sall = stats_pool(dte['features']); s4 = sall[mask4]
    sd = s4.shape[-1]

    Ld = head_logits(load_head(os.path.join(CKPT, 'direct4_s314.pt'), 4, 384, 8, 6, sd, dev, TH), s4, dev)
    Lsc = head_logits(load_head(os.path.join(CKPT, 'scenario_s7.pt'), 4, 384, 8, 6, sd, dev, TH), sall, dev)[mask4]
    pair_log = []
    for i, n in enumerate(PAIR_NAMES):
        pair_log.append(head_logits(load_head(os.path.join(CKPT, f'pair{i}_{n}_s7.pt'), 2, 192, 6, 3, sd, dev, TH), s4, dev))
    pair_log = np.stack(pair_log, 1)

    Pd = F.softmax(torch.from_numpy(Ld), 1).numpy()
    Psc = F.softmax(torch.from_numpy(Lsc), 1).numpy()
    Pp_unsafe = F.softmax(torch.from_numpy(pair_log), 2).numpy()[:, :, 1]
    cas = Psc * Pp_unsafe; cas = cas / (cas.sum(1, keepdims=True) + 1e-8)
    ens = (Pd + cas) / 2
    ens_pred = ens.argmax(1)

    # NB: clip-index ordering is the load order from all8_test.pt restricted to mask4.
    # mask4 selects label < 4 in original index order; we record both indices for traceability.
    orig_idx = np.where(mask4)[0]

    print(f"Writing {len(y)} rows to {OUT}")
    with open(OUT, 'w', newline='') as f:
        f.write(LICENSE_HEADER)
        w = csv.writer(f)
        header = (['clip_index_4cls', 'clip_index_8cls_orig', 'true_label', 'true_class']
                  + [f'direct4_logit_{c}' for c in range(4)]
                  + [f'direct4_prob_{c}' for c in range(4)]
                  + [f'cascade_prob_{c}' for c in range(4)]
                  + [f'ensemble_prob_{c}' for c in range(4)]
                  + ['ensemble_pred', 'ensemble_pred_class', 'correct'])
        w.writerow(header)
        for i in range(len(y)):
            row = [
                int(i),
                int(orig_idx[i]),
                int(y[i]),
                CLASS_NAMES[int(y[i])],
                *[round(float(x), 6) for x in Ld[i]],
                *[round(float(x), 6) for x in Pd[i]],
                *[round(float(x), 6) for x in cas[i]],
                *[round(float(x), 6) for x in ens[i]],
                int(ens_pred[i]),
                CLASS_NAMES[int(ens_pred[i])],
                int(ens_pred[i] == y[i]),
            ]
            w.writerow(row)

    n_correct = int((ens_pred == y).sum())
    print(f"\nEnsemble: {n_correct}/{len(y)} = {100 * n_correct / len(y):.2f} %")
    print(f"[SAVED] {OUT}")


if __name__ == '__main__':
    main()
